test "ascii passes through" {
    try std.testing.expectEqual(@as(?u8, 'A'), Encoding.cp437.encode('A'));
    try std.testing.expectEqual(@as(?u8, 0x0a), Encoding.cp858.encode('\n'));
}

test "accented letters" {
    try std.testing.expectEqual(@as(?u8, 0x82), Encoding.cp437.encode(0xe9));
    try std.testing.expectEqual(@as(?u8, 0x82), Encoding.cp858.encode(0xe9));
    try std.testing.expectEqual(@as(?u8, 0xe9), Encoding.cp1252.encode(0xe9));
}

test "euro sign" {
    try std.testing.expectEqual(@as(?u8, null), Encoding.cp437.encode(0x20ac));
    try std.testing.expectEqual(@as(?u8, 0xd5), Encoding.cp858.encode(0x20ac));
    try std.testing.expectEqual(@as(?u8, 0x80), Encoding.cp1252.encode(0x20ac));
}

test "unmapped characters" {
    try std.testing.expectEqual(@as(?u8, null), Encoding.cp1252.encode(0x4e2d));
    // 0x81 is undefined in Windows-1252
    try std.testing.expectEqual(@as(?u8, null), Encoding.cp1252.encode(0x81));
}
