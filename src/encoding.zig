//! UTF-8 to printer code page conversion for the code pages built into Epson
//! printers. Each table maps bytes 0x80-0xFF to Unicode scalar values; bytes
//! below 0x80 are ASCII in all of them. A zero entry is unmapped.
//!
//! The tables were generated from Python's cp437, cp858 and cp1252 codecs.
const std = @import("std");

/// A printer code page that UTF-8 text can be converted to.
pub const Encoding = enum {
    /// PC437, the US default (ESC t 0).
    cp437,
    /// PC858, Western European with the euro sign (ESC t 19).
    cp858,
    /// WPC1252, Windows Western European (ESC t 16).
    cp1252,

    /// The argument to ESC t that selects this code page on Epson printers.
    pub fn codePage(self: Encoding) u8 {
        return switch (self) {
            .cp437 => 0,
            .cp858 => 19,
            .cp1252 => 16,
        };
    }

    fn table(self: Encoding) *const [128]u21 {
        return switch (self) {
            .cp437 => &cp437,
            .cp858 => &cp858,
            .cp1252 => &cp1252,
        };
    }

    /// Encode one Unicode scalar value, or null if this code page lacks it.
    pub fn encode(self: Encoding, cp: u21) ?u8 {
        if (cp < 0x80) return @intCast(cp);
        if (cp == 0) return null;
        for (self.table(), 0..) |c, i| {
            if (c == cp) return @intCast(0x80 + i);
        }
        return null;
    }
};

/// Written for characters that are invalid UTF-8 or missing from the code page.
pub const replacement = '?';

